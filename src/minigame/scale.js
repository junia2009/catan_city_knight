// 棒人間の縮尺。
//
// **島の広さは盤で決まっていて増やせない**(陸19枚・端から端まで 6.93 タイル)。
// そこで、島を大きくする代わりに歩く人のほうを小さくしてある ── island に
// 対する相対的な広さが 1/縮尺 倍になり、盤を作り直さずに島が広くなる。
//
// ×0.5 での実測:
//   端から端まで  3.6秒 → 7.3秒(航海者の盤を等倍で歩くより広い)
//   外周を1周     11秒 → 23秒
//   木の見かけ    自分の1.5倍 → 3.0倍(大木は6倍。ここで初めて隠れられる)
//
// **カメラの距離も同じ率で縮める**ので、棒人間が画面に占める大きさは変わらない。
// 変わるのは「一度にどれだけ島が見えるか」だけ ── 実質、島に対する
// ズームアウトになっている。
//
// 何を掛けて、何を掛けないか:
//   掛ける   … 人の寸法・速さ・跳躍・当たり半径・カメラの距離・
//              「どこまで近づけるか」の距離(受付・釣り場)
//   掛けない … 盤の寸法(タイルの高さ・海面・港の看板の位置)、
//              時間と角速度(滞空 0.8 秒・向き変えの速さ・水の抵抗)
// 時間を掛けないので、歩き出しも跳躍も**テンポは今までどおり**で、
// 進む距離だけが縮む。
export const WALK_SCALE = 0.5;

// 「人まわりの長さ」に掛ける。掛け忘れを見つけやすいように、
// 直に 0.5 と書かずに必ずこれを通す。
export const s = (v) => v * WALK_SCALE;
